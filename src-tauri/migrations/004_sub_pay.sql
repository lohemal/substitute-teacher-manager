-- 보결 수당 설정.
--
-- 수당은 학교마다 지급 규정이 다르므로 설정값으로 둔다. 계산 결과 자체는
-- 저장하지 않는다 — 조회할 때마다 `substitutions` 원본에서 다시 센다.
-- 그래서 배정을 취소하거나 금액을 바꾸면 다음 조회에 곧바로 반영된다.
--
-- 여기서 넣는 것은 **설정 기본값 두 줄뿐**이다. 기존 교사·시정표·전담
-- 시간표·결근·보결 배정·학기·백업 자료는 손대지 않는다.
--
-- 값이 없어도 프로그램은 기본값으로 동작하지만, 처음부터 행을 만들어 두면
-- 설정 화면이 '기본값과 다른가'를 판단하기 쉽고 백업에도 함께 남는다.

INSERT OR IGNORE INTO settings(key, value_json) VALUES
  -- 1회 보결 수당(원). 0 이상 정수. 학교가 정하기 전까지는 0원이다.
  ('sub_pay_per_case', '0'),
  -- 지급 기준 정책 코드. ALL_ASSIGNED | DEDUCT_OWN_CAUSED
  ('sub_pay_policy',   '"ALL_ASSIGNED"');
