-- ============================================================
--  반 이름 (schema version 2)
--
--  학교마다 반을 '1반, 2반'으로 부르기도 하고 '가람반, 나리반'처럼
--  이름으로 부르기도 한다.
--
--  `class_no`는 그대로 둔다. 순서·식별·정렬의 기준이므로 이름을 바꿔도
--  시간표나 보결 기록이 깨지지 않는다. `name`은 표시용이며 NULL이면
--  숫자로 표기한다.
--
--  표시 형태
--    이름 있음 : 5-가람   / 5학년 가람반
--    이름 없음 : 5-1      / 5학년 1반
-- ============================================================

ALTER TABLE classes ADD COLUMN name TEXT;

-- 한 학년 안에서 반 이름이 겹치면 안 된다
CREATE UNIQUE INDEX ux_classes_name
  ON classes(term_id, grade, name) WHERE name IS NOT NULL;

-- ------------------------------------------------------------
--  과거 보결 기록의 반 이름 고정
--
--  새 학년도·학기에 반 이름이 바뀌어도 지난 기록의 표기는 그대로여야 한다.
--  시각(start_min)을 스냅샷한 것과 같은 원칙으로 반 이름도 복사해 둔다.
--  NULL이면 grade/class_no로 만들어 보여 준다(이 컬럼이 생기기 전 기록).
-- ------------------------------------------------------------

ALTER TABLE substitutions ADD COLUMN class_label TEXT;
